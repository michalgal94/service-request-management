export function seedDatabaseIfEmpty(db: DatabaseSync): boolean {
  db.exec('BEGIN IMMEDIATE');
  try {
    const { count } = db.prepare('SELECT COUNT(*) AS count FROM tickets').get() as { count: number };
    if (count > 0) {
      db.exec('COMMIT');
      return false;
    }
    const insert = db.prepare('INSERT INTO tickets (title, description, status, created_at) VALUES (?, ?, ?, ?)');
    const now = Date.now();
    for (let index = examples.length - 1; index >= 0; index--) {
      const [title, description] = examples[index]!;
      insert.run(title, description, ticketStatuses[index % ticketStatuses.length]!,
        new Date(now - (index + 1) * 6 * 60 * 60 * 1000).toISOString());
    }
    db.exec('COMMIT');
    return true;
  } catch (error) {
    db.exec('ROLLBACK');
    throw error;
  }
}
